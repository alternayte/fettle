#!/usr/bin/env bash
# Writes internal/app/migrations_gen.go from the modules in drel.yaml.
set -euo pipefail
cd "$(dirname "$0")/.."
mods=$(grep -oE 'name: [a-z]+' drel.yaml | awk '{print $2}')
out=internal/app/migrations_gen.go
{
  echo '// Code generated by scripts/gen-migrations.sh. DO NOT EDIT.'
  echo
  echo 'package app'
  echo
  echo 'import ('
  echo '	"io/fs"'
  echo
  for m in $mods; do
    echo "	${m}pg \"github.com/alternayte/fettle/internal/$m/migrations/postgres\""
    echo "	${m}lite \"github.com/alternayte/fettle/internal/$m/migrations/sqlite\""
  done
  echo ')'
  echo
  echo '// migrationSets returns the embedded migrations of every drel module for one dialect.'
  echo 'func migrationSets(postgres bool) []fs.FS {'
  echo '	if postgres {'
  printf '		return []fs.FS{'
  sep=""; for m in $mods; do printf '%s%spg.FS' "$sep" "$m"; sep=", "; done; echo '}'
  echo '	}'
  printf '	return []fs.FS{'
  sep=""; for m in $mods; do printf '%s%slite.FS' "$sep" "$m"; sep=", "; done; echo '}'
  echo '}'
} > "$out"
gofmt -w "$out"
